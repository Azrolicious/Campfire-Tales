-- The buttons of a category as { label = ..., lines = { ... } }, made once.
-- Each also carries its category's beat and the name of its last line.
function T.Entries(category)
	if not category.entries then
		local entries = {}
		for index, button in ipairs(category) do
			local lines = {}
			for line = 2, #button do
				lines[#lines + 1] = button[line]
			end
			entries[index] = { label = button[1], lines = lines, beat = category.beat, last = category.last,
				crude = button.crude or category.crude or nil }
		end
		category.entries = entries
	end
	return category.entries
end
