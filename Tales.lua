-- Everything Campfire Tales can say, sorted into the categories down the
-- left of the window.
--
-- Each category has a key, a name and a line about it, then its buttons.
-- A button is { "Button label", "first line", "second line", ... }:
--   * A line is said out loud (/say), unless it starts with /e, which makes it
--     an action (an emote), or /y, which yells it.
--   * A button with more than one line is told one line at a time. Each line
--     goes into the chat line; press Enter to say it and the next one follows.
--
-- Words in curly brackets are filled in when the line is said:
--   {target}           your target's name, or "friend" without one
--   {target:everyone}  your target's name, or the word after the colon
--   {me}               your character's name
--   {zone}             where you are: the subzone, or else the zone
--   {time}             morning, afternoon or evening, by the game's clock
--   {his} {him} {he}   her and she for a female character
--
-- Keep each line under about 180 letters. Krump and Juju make lines longer
-- when they put them in their accent, and a line that grows too long for
-- chat is sent as it was typed.

